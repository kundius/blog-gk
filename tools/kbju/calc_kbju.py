# None — если единица для этого продукта не применима (берётся дефолт).
def R(kcal, p, f, c, piece=None, cup=None, tbsp=None, tsp=None, banka=None,
      pack=None, **extra):
    d = {'kcal': kcal, 'p': p, 'f': f, 'c': c}
    for k, v in (('piece', piece), ('cup', cup), ('tbsp', tbsp), ('tsp', tsp),
                 ('banka', banka), ('pack', pack)):
        if v is not None:
            d[k] = v
    d.update(extra)
    return d

