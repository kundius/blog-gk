def normalize(name):
    s = name.lower().replace('ё', 'е')
    s = re.sub(r'^\s*\d+[\.\)]\s*', '', s)          # нумерация "1. хрен"
    s = re.sub(r'^\s*(для|на|из)\s+', '', s)
    s = re.split(r'\s+(или|либо)\s+', s)[0]          # "а или б" -> "а"
    s = s.split('+')[0]
    s = re.sub(r'\([^)]*\)', '', s)                  # скобки
    s = re.split(r'\s+для\s+', s)[0]                 # "X для Y" -> "X"
    s = s.strip().rstrip(':').strip()
    words = [w for w in s.split() if w not in STOP]
    return ' '.join(sorted(set(words)))


def sort_words(text):
    return ' '.join(sorted(set(text.split())))


def match_ref(name):
    nm = normalize(name)
    best, bestlen = None, 0
    for key in KBJU:
        k = sort_words(key)
        if len(k) >= bestlen and k in nm:
            best, bestlen = key, len(k)
    return best


