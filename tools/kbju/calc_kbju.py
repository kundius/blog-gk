"""Расчёт приблизительного КБЖУ (на 100 г сырых ингредиентов) для всех рецептов.

Для каждого рецепта (articles.ingredients: JSON [{name, amount|value}]) скрипт:
  1. нормализует название ингредиента и подбирает его КБЖУ на 100 г из
     встроенного справочника (значения — приблизительные, по типовым продуктам);
  2. переводит количество (value/amount) в граммы (г/кг/мг/мл/л, стакан,
     столовая/чайная ложка, шт, долька, зубчик, листик, банка, пачка и т.п.);
  3. суммирует по рецепту КБЖУ и общий вес всех ингредиентов;
  4. считает значения на 100 г: nutrient * 100 / total_weight;
  5. пишет результат (строка, 1 знак после запятой, разделитель — точка)
     в существующие поля articles: calories, protein, fat, carbs.

Нераспознанные ингредиенты, а также «по вкусу»/«щепотка» и т.п. считаются с
нулевым весом и на расчёт не влияют. Если у рецепта общий вес = 0 — он
пропускается.

Данные берутся напрямую из БД (docker compose exec postgres psql). Запускать
на хосте (python3, только стандартная библиотека) из корня репозитория.

Примеры:
  python3 tools/kbju/calc_kbju.py            # dry-run: статистика + пример
  python3 tools/kbju/calc_kbju.py --apply    # записать в БД (с авто-бэкапом)
  python3 tools/kbju/calc_kbju.py --force    # пересчитать уже заполненные
"""
