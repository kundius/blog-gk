def parse_amount(text, ref):
    t = (text or '').lower()
    t = re.sub(r'[–—]', '-', t)
    for w, d in NUMWORD.items():
        t = re.sub(r'\b' + w + r'\b', d, t)
    t = re.sub(r'(\d+)\s+(\d+)\s*/\s*(\d+)',
               lambda m: str(int(m.group(1)) + int(m.group(2)) / int(m.group(3))), t)
    t = re.sub(r'(\d+)\s*/\s*(\d+)', lambda m: str(int(m.group(1)) / int(m.group(2))), t)
    t = re.sub(r'(\d+(?:\.\d+)?)\s*-\s*(\d+(?:\.\d+)?)',
               lambda m: str((float(m.group(1)) + float(m.group(2))) / 2), t)
    t = re.sub(r'\s+', ' ', t).strip()
    has_plus = '+' in t

    toks = re.findall(r'\d+(?:\.\d+)?|[а-яё]+', t)
    pairs = []
    i = 0
    while i < len(toks):
        tok = toks[i]
        if re.fullmatch(r'\d+(?:\.\d+)?', tok):
            qty = float(tok)
            unit = None
            for j in range(i + 1, min(i + 3, len(toks))):
                u = classify_unit(toks[j])
                if u:
                    unit = u
                    break
            if unit is None:
                unit = 'g'  # число без единицы -> граммы
            pairs.append((i, unit, qty))
        i += 1

    if not pairs:
        # нет чисел — возможно "неполный стакан", "стакан" и т.п.
        for tok in toks:
            u = classify_unit(tok)
            if u:
                qty = 0.8 if 'неполн' in t else 1.0
                return unit_grams(u, qty, ref)
        return 0.0

    if has_plus:
        return sum(unit_grams(u, q, ref) for _, u, q in pairs)

    # предпочитаем явный вес (г/кг/мг/мл/л), иначе первый по порядку
    for _, u, q in pairs:
        if u in ('g', 'kg', 'mg', 'ml', 'l'):
            return unit_grams(u, q, ref)
    _, u, q = pairs[0]
    return unit_grams(u, q, ref)


# --- DB helpers -------------------------------------------------------------
def psql(sql):
    r = subprocess.run(DB + ['-c', sql], capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f'psql failed: {r.stderr.strip()}')
    return r.stdout


def check_repo_root():
    if not os.path.exists('docker-compose.yml'):
        print('error: run from repository root (docker-compose.yml required)',
              file=sys.stderr)
        sys.exit(2)


def fetch_articles(force):
    cond = ''
    if not force:
        cond = " AND (calories IS NULL OR calories = '')"
    out = psql(
        "SELECT to_json(t) FROM articles t "
        "WHERE ingredients IS NOT NULL" + cond + ';')
    rows = []
    for line in out.split('\n'):
        line = line.strip()
        if not line:
            continue
        try:
            a = json.loads(line)
        except (ValueError, json.JSONDecodeError):
            continue
        rows.append((a['id'], a.get('name') or '', a.get('ingredients') or []))
    return rows


def compute(recipe_id, name, ingredients):
    tot = {'kcal': 0.0, 'p': 0.0, 'f': 0.0, 'c': 0.0, 'w': 0.0}
    unmatched = []
    for ing in ingredients:
        iname = ing.get('name') or ''
        amount = ing.get('value') or ing.get('amount') or ''
        ref = match_ref(iname)
        if ref is None:
            unmatched.append(iname)
            continue
        grams = parse_amount(amount, KBJU[ref])
        r = KBJU[ref]
        tot['w'] += grams
        tot['kcal'] += r['kcal'] * grams / 100.0
        tot['p'] += r['p'] * grams / 100.0
        tot['f'] += r['f'] * grams / 100.0
        tot['c'] += r['c'] * grams / 100.0
    if tot['w'] <= 0:
        return None, tot, unmatched
    out = {
        'calories': round(tot['kcal'] * 100.0 / tot['w'], 1),
        'protein': round(tot['p'] * 100.0 / tot['w'], 1),
        'fat': round(tot['f'] * 100.0 / tot['w'], 1),
        'carbs': round(tot['c'] * 100.0 / tot['w'], 1),
    }
    return out, tot, unmatched


def fmt(v):
    return f'{v:.1f}'.replace('.', '.')


def apply_to_db(updates):
    ts = datetime.datetime.now().strftime('%Y%m%d_%H%M%S')
    backup_dir = os.path.join(BASE, 'backups')
    os.makedirs(backup_dir, exist_ok=True)
    backup = os.path.join(backup_dir, f'pre_{ts}.sql')
    r = subprocess.run(['docker', 'compose', 'exec', '-T', 'postgres', 'pg_dump',
                        '-U', 'blog_gk_user', '-d', 'blog_gk_db'], capture_output=True)
    with open(backup, 'wb') as f:
        f.write(r.stdout)
    print(f'backup -> {backup}')

    vals = ',\n'.join(
        "('%s'::uuid,'%s','%s','%s','%s')" % (cid, v['calories'], v['protein'], v['fat'], v['carbs'])
        for cid, v in updates)
    sql = '\n'.join([
        'BEGIN;',
        'UPDATE articles AS t SET calories=v.k, protein=v.p, fat=v.f, carbs=v.c '
        'FROM (VALUES %s) AS v(id,k,p,f,c) WHERE t.id=v.id;' % vals,
        'COMMIT;',
    ])
    r = subprocess.run(DB + ['-f', '-'], input=sql, capture_output=True, text=True)
    print(r.stdout, end='')
    if r.stderr.strip():
        print(r.stderr, file=sys.stderr)


def main():
    ap = argparse.ArgumentParser(description='Calculate approximate KBJU per 100g for recipes')
    ap.add_argument('--apply', action='store_true', help='write results to DB (default: dry-run)')
    ap.add_argument('--force', action='store_true', help='recompute already-filled recipes')
    args = ap.parse_args()

    check_repo_root()
    articles = fetch_articles(args.force)

    updates = []
    skipped = 0
    unmatched_all = {}
    total_ing = 0
    matched_ing = 0
    for cid, name, ingredients in articles:
        total_ing += len(ingredients)
        out, tot, unmatched = compute(cid, name, ingredients)
        matched_ing += len(ingredients) - len(unmatched)
        for u in unmatched:
            unmatched_all[u] = unmatched_all.get(u, 0) + 1
        if out is None:
            skipped += 1
            continue
        updates.append((cid, out))

    print(f'articles={len(articles)} filled={len(updates)} skipped(weight=0)={skipped}')
    print(f'ingredients={total_ing} matched={matched_ing} unmatched={total_ing - matched_ing}')

    print('\n--- top unmatched ingredients ---')
    for nm, cnt in sorted(unmatched_all.items(), key=lambda x: -x[1])[:25]:
        print(f'  {cnt:5d}  {nm}')

    print('\n--- example ---')
    for cid, v in updates[:5]:
        print(f'  {cid} calories={v["calories"]} protein={v["protein"]} '
              f'fat={v["fat"]} carbs={v["carbs"]}')

    if args.apply and updates:
        apply_to_db(updates)
    elif args.apply:
        print('nothing to apply')


if __name__ == '__main__':
    main()